  defp player do
    %Kalevala.Character{
      id: "player-1",
      name: "张三",
      pid: self(),
      room_id: "test:room",
      inventory: [],
      attributes: %{"wiz_level" => 0},
      meta: %PlayerMeta{
        vitals: Vitals.new(),
        stats: Stats.new(),
        combat: Kantele.Character.Combat.new()
      }
    }
  end

  defp conn_for do
    p = player()
    room = %{name: "测试房间", exits: %{}, items: [], characters: []}
    build_conn(p) |> Map.put(:room, room)
  end

  for verb <- @verbs do
    test "裸输入 #{verb} 可解析不崩溃" do
      conn = conn_for()

      try do
        result = Kantele.Character.Commands.call(conn, unquote(verb))

        if unquote(verb) in @arg_verbs do
          # 需参数动词：裸输入返回 {:error, :unknown} 是既有设计（见迁移文档），仅断言不崩溃
          assert result == {:error, :unknown} or is_map(result)
        else
          # 无参数动词：裸输入必须可解析
          refute result == {:error, :unknown},
                 "裸指令 `#{unquote(verb)}` 本应可解析，却返回 {:error, :unknown}"
        end
      rescue
        e ->
          flunk("裸指令 `#{unquote(verb)}` 崩溃: #{Exception.message(e)}")
      catch
        kind, value ->
          flunk("裸指令 `#{unquote(verb)}` 崩溃: #{inspect(kind)} #{inspect(value)}")
      end
    end

    test "带参输入 #{verb} 测试 不崩溃" do
      conn = conn_for()

      try do
        _ = Kantele.Character.Commands.call(conn, unquote(verb) <> " 测试")
      rescue
        e ->
          flunk("带参指令 `#{unquote(verb)} 测试` 崩溃: #{Exception.message(e)}")
      catch
        kind, value ->
          flunk("带参指令 `#{unquote(verb)} 测试` 崩溃: #{inspect(kind)} #{inspect(value)}")
      end
    end
  end
